-- Client idempotency for withdrawals.
--
-- A double click, a browser retry after a dropped connection or two open tabs
-- used to create two separate withdrawals (each one correctly balance-checked, so
-- the balance never went negative, but the user paid twice for one action).
-- The client now sends an Idempotency-Key per withdrawal intent; the same key
-- returns the withdrawal created the first time instead of creating another one.

begin;

alter table public.transactions add column idempotency_key text;

comment on column public.transactions.idempotency_key is
  'Client-supplied key (Idempotency-Key header) of the request that created this withdrawal.';

-- Scoped per user: keys are generated by clients, not globally unique by contract.
create unique index transactions_user_idempotency_key_idx
  on public.transactions (user_id, idempotency_key)
  where idempotency_key is not null;

-- Like before plus p_idempotency_key; returns (replayed, tx):
--  * new key            -> reserve funds, create the withdrawal, replayed = false;
--  * key already used   -> that withdrawal with replayed = true, nothing reserved twice;
--  * same key, other token/amount/destination -> 'idempotency_key_reused'.
-- Concurrency: requests with the same key and token serialise on the balance
-- row lock and the second one finds the first one's row. With a different
-- token they do not share a lock; then the unique index decides and the loser
-- reads the winner's row.
drop function public.create_withdrawal(uuid, text, numeric, text);

create function public.create_withdrawal(
  p_user_id         uuid,
  p_token_id        text,
  p_amount          numeric,
  p_destination     text,
  p_idempotency_key text default null
)
returns table (replayed boolean, tx public.transactions_api)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_replayed  boolean := false;
  v_address   text;
  v_available numeric;
  v_id        uuid;
begin
  if p_amount is null or p_amount <= 0 then
    raise exception 'invalid_amount' using errcode = 'P0001';
  end if;

  select address into v_address from public.users where id = p_user_id;
  if not found then
    raise exception 'user_not_found' using errcode = 'P0001';
  end if;

  select available into v_available
  from public.balances
  where user_id = p_user_id and token_id = p_token_id
  for update;

  -- Replay? Checked after taking the lock, so a concurrent first request has committed.
  if p_idempotency_key is not null then
    v_id := public.find_withdrawal_by_key(p_user_id, p_idempotency_key, p_token_id, p_amount, p_destination);
    if v_id is not null then
      return query select true, t from public.transactions_api t where t.id = v_id;
      return;
    end if;
  end if;

  if coalesce(v_available, 0) < p_amount then
    raise exception 'insufficient_funds' using errcode = 'P0001';
  end if;

  begin
    insert into public.transactions (
      user_id, direction, status, token_id, amount, source_address, destination_address, idempotency_key
    ) values (
      p_user_id, 'withdrawal', 'pending', p_token_id, p_amount, v_address, p_destination, p_idempotency_key
    )
    returning id into v_id;
  exception when unique_violation then
    -- Lost a race with a request that used the same key for another token.
    v_id := public.find_withdrawal_by_key(p_user_id, p_idempotency_key, p_token_id, p_amount, p_destination);
    v_replayed := true;
  end;

  return query select v_replayed, t from public.transactions_api t where t.id = v_id;
end
$$;

-- The withdrawal created earlier with this key, or null. Raises
-- 'idempotency_key_reused' if the key was used for a different request.
create function public.find_withdrawal_by_key(
  p_user_id         uuid,
  p_idempotency_key text,
  p_token_id        text,
  p_amount          numeric,
  p_destination     text
)
returns uuid
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_tx public.transactions;
begin
  select * into v_tx
  from public.transactions
  where user_id = p_user_id and idempotency_key = p_idempotency_key;

  if not found then
    return null;
  end if;

  if v_tx.direction <> 'withdrawal'
     or v_tx.token_id <> p_token_id
     or v_tx.amount <> p_amount
     or lower(v_tx.destination_address) <> lower(p_destination) then
    raise exception 'idempotency_key_reused' using errcode = 'P0001';
  end if;

  return v_tx.id;
end
$$;

revoke execute on function public.create_withdrawal(uuid, text, numeric, text, text) from public, anon, authenticated;
revoke execute on function public.find_withdrawal_by_key(uuid, text, text, numeric, text) from public, anon, authenticated;
grant execute on function public.create_withdrawal(uuid, text, numeric, text, text) to service_role;

commit;
